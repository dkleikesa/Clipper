package com.qcmian.clipper.devtools.tools.hash

/**
 * 本工具支持的摘要算法，按「家族 + 摘要长度」排列。
 *
 * 覆盖开发者常用的几档密码学 hash：MD5、SHA-1（已不耐碰撞，但校验对拍、老接口兼容仍天天用），
 * SHA-2 全家族（含 SHA-224），以及新一代 SHA-3。它们与 Base64 工具「解出来是什么就是什么、
 * 不去判断是否敏感」同一个态度——这里的用法是**生成 / 对拍**，不是安全防护。
 *
 * 最后一个 [CRC32] 只是校验和，它不抗碰撞，特意排在末尾，免得被当成摘要用。
 *
 * [digestBytes] 是摘要的字节长度：界面据此对齐标签列，测试据此校验长度，免得某一个算法悄悄
 * 返回了截断或补齐的值。
 */
internal enum class HashAlgorithm(
    /** 标签与复制提示里的显示名。 */
    val displayName: String,
    /** 摘要的字节数。 */
    val digestBytes: Int,
) {
    MD5("MD5", 16),
    SHA1("SHA-1", 20),

    /** SHA-2：与 SHA-256 同族，摘要 28 字节。 */
    SHA224("SHA-224", 28),
    SHA256("SHA-256", 32),
    SHA384("SHA-384", 48),
    SHA512("SHA-512", 64),

    /** SHA-3（Keccak 标准化后的版本）：与 SHA-2 是两套不同的构造，摘要长度一一对应。 */
    SHA3_224("SHA3-224", 28),
    SHA3_256("SHA3-256", 32),
    SHA3_384("SHA3-384", 48),
    SHA3_512("SHA3-512", 64),

    /** 非密码学校验和：IEEE 802.3 反射 CRC-32，4 字节。 */
    CRC32("CRC32", 4),
}
